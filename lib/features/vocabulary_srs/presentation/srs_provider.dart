class SrsDeckNotifier extends Notifier<List<FlashcardEntity>> {
  @override
  List<FlashcardEntity> build() {
    final now = DateTime.now();
    _loadAndMergeFromLocalDb(now);
    return _defaultCards(now);
  }

  /// Merges persisted progress with the full 30-word curriculum so new fields & cards always appear.
  Future<void> _loadAndMergeFromLocalDb(DateTime now) async {
    final storage = ref.read(localStorageServiceProvider);
    final rawList = await storage.getJsonList(storage.keySrsCards);
    if (rawList.isEmpty) return;

    final baseMap = <String, FlashcardEntity>{
      for (final c in _defaultCards(now)) c.id: c,
    };

    for (final raw in rawList) {
      final saved = FlashcardEntity.fromJson(raw);
      if (baseMap.containsKey(saved.id)) {
        final fresh = baseMap[saved.id]!;
        baseMap[saved.id] = fresh.copyWith(
          repetition: saved.repetition,
          easeFactor: saved.easeFactor,
          intervalDays: saved.intervalDays,
          nextReviewDate: saved.nextReviewDate,
        );
      } else {
        baseMap[saved.id] = saved;
      }
    }
    state = baseMap.values.toList();
  }

  Future<void> _persistDeck() async {
    final storage = ref.read(localStorageServiceProvider);
    await storage.setJsonList(
      storage.keySrsCards,
      state.map((c) => c.toJson()).toList(),
    );
  }

  Future<void> gradeCard(String cardId, SrsGrade grade, {bool awardXp = true}) async {
    state = [
      for (final card in state)
        if (card.id == cardId) card.review(grade) else card,
    ];
    if (awardXp) {
      ref.read(gamificationProvider.notifier).addXp(5);
    }
    await _persistDeck();
  }

  Future<void> addCustomCard({
    required String word,
    required String ipa,
    required String partOfSpeech,
    required String vietnameseMeaning,
    required String exampleSentence,
    String grammarNote = '',
    String topic = 'Từ vựng Cá nhân',
  }) async {
    final newCard = FlashcardEntity(
      id: 'card_${DateTime.now().millisecondsSinceEpoch}',
      word: word,
      ipa: ipa.isEmpty ? '/${word.toLowerCase()}/' : ipa,
      cefr: 'B1',
      partOfSpeech: partOfSpeech,
      vietnameseMeaning: vietnameseMeaning,
      exampleSentence: exampleSentence,
      topic: topic,
      grammarNote: grammarNote.isEmpty
          ? 'Từ vựng cá nhân bạn đã thêm vào bộ thẻ Offline.'
          : grammarNote,
      usageTip: 'Hãy đặt ít nhất 2 câu thực tế với từ này để ghi nhớ sâu.',
      collocations: [word],
      wordFamily: word,
      nextReviewDate: DateTime.now(),
    );
    state = [newCard, ...state];
    await _persistDeck();
  }

